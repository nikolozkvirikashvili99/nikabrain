#!/usr/bin/env node
// Wire nikabrain into ~/.claude. Idempotent: safe to re-run after every pull, and on a new
// machine after cloning to ~/projects/nikabrain. Nika runs this; Claude doesn't (changes to
// Claude's own config need a human: brain/patterns/claude-config-changes-need-human-installer.md).
//
//   node bin/install.mjs            dry run: print what would change, change nothing
//   node bin/install.mjs --apply    do it (backs up anything it replaces into ~/.claude/backups/)
//   node bin/install.mjs --uninstall [--apply]   remove nikabrain's links, hooks and CLAUDE.md
//
// What it does:
//   1. ~/.claude/CLAUDE.md          generated 3-line file that @imports brain/CORE.md (no symlink needed)
//   2. ~/.claude/skills/<name>      directory junctions -> global/skills/* and library/skills/*
//   3. ~/.claude/agents             junction -> global/agents (or per-file copies if you already have agents)
//   4. ~/.claude/settings.json      += hooks (coach, guard, session-log), cleanupPeriodDays 365,
//                                    ask before git push, Read access to nikabrain/library for reviewers
//   5. git core.hooksPath=.githooks in nikabrain (secret scan on every commit)
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { ROOT, HOME, CLAUDE_DIR, fwd, readJSON, listDirs, today } from './lib.mjs';

const APPLY = process.argv.includes('--apply');
const UNINSTALL = process.argv.includes('--uninstall');
const C = CLAUDE_DIR;
const BACKUPS = path.join(C, 'backups');
const MARK = '<!-- generated by nikabrain/bin/install.mjs: edit nikabrain, not this file -->';
const log = (s) => console.log(s);
const act = (desc, fn) => { log(`  ${APPLY ? '' : '[dry] '}${desc}`); if (APPLY) fn(); };

function backup(p) {
  const dest = path.join(BACKUPS, `${path.basename(p)}.pre-nikabrain-${today()}`);
  act(`back up ${p} -> ${dest}`, () => { fs.mkdirSync(BACKUPS, { recursive: true }); fs.renameSync(p, dest); });
}

const isLink = (p) => { try { return fs.lstatSync(p).isSymbolicLink(); } catch { return false; } };
const exists = (p) => { try { fs.lstatSync(p); return true; } catch { return false; } };
const linkTarget = (p) => { try { return path.resolve(path.dirname(p), fs.readlinkSync(p)); } catch { return null; } };
const same = (a, b) => a && b && path.resolve(a).toLowerCase() === path.resolve(b).toLowerCase();

function junction(target, link) {
  if (isLink(link)) {
    if (same(linkTarget(link), target)) { log(`  ok  ${link}`); return; }
    act(`relink ${link} -> ${target}`, () => { fs.unlinkSync(link); fs.symlinkSync(target, link, 'junction'); });
    return;
  }
  if (exists(link)) backup(link);
  act(`link ${link} -> ${target}`, () => fs.symlinkSync(target, link, 'junction'));
}

// ---- 1. CLAUDE.md ----
function claudeMd() {
  log('1. ~/.claude/CLAUDE.md');
  const f = path.join(C, 'CLAUDE.md');
  const core = path.join(ROOT, 'brain', 'CORE.md');
  const rel = path.relative(HOME, core);
  const ref = rel.startsWith('..') || path.isAbsolute(rel) ? fwd(core) : `~/${fwd(rel)}`;
  const body = `${MARK}\n# Global instructions\n\nThe user is Nika. Their curated cross-project brain is imported below: the habits and\ndefaults that apply in every repo. Project CLAUDE.md files add to it; they don't replace it.\n\n@${ref}\n`;
  if (UNINSTALL) {
    if (exists(f) && fs.readFileSync(f, 'utf8').startsWith(MARK)) act(`remove ${f}`, () => fs.unlinkSync(f));
    return;
  }
  if (exists(f)) {
    const cur = fs.readFileSync(f, 'utf8');
    if (cur === body) { log(`  ok  ${f}`); return; }
    if (!cur.startsWith(MARK)) backup(f);
  }
  act(`write ${f} (imports ${ref})`, () => fs.writeFileSync(f, body));
}

// ---- 2. skills ----
function skills() {
  log('2. skills -> ~/.claude/skills/');
  const dir = path.join(C, 'skills');
  if (APPLY) fs.mkdirSync(dir, { recursive: true });
  const ours = new Map();
  for (const n of listDirs(path.join(ROOT, 'global', 'skills'))) ours.set(n, path.join(ROOT, 'global', 'skills', n));
  for (const n of listDirs(path.join(ROOT, 'library', 'skills'))) {
    if (ours.has(n)) { log(`  SKIP library/${n}: name taken by global/skills/${n}`); continue; }
    ours.set(n, path.join(ROOT, 'library', 'skills', n));
  }
  // links into nikabrain whose skill is gone (retired by /curate) or, on uninstall, all of ours
  for (const n of (exists(dir) ? fs.readdirSync(dir) : [])) {
    const p = path.join(dir, n);
    if (!isLink(p)) continue;
    const t = linkTarget(p) || '';
    if (!t.toLowerCase().startsWith(ROOT.toLowerCase())) continue;
    if (UNINSTALL || !ours.has(n) || !exists(t)) act(`remove link ${p}`, () => fs.unlinkSync(p));
  }
  if (UNINSTALL) return;
  for (const [n, target] of ours) junction(target, path.join(dir, n));
}

// ---- 3. agents ----
function agents() {
  log('3. agents -> ~/.claude/agents');
  const dir = path.join(C, 'agents');
  const src = path.join(ROOT, 'global', 'agents');
  if (UNINSTALL) {
    if (isLink(dir) && same(linkTarget(dir), src)) act(`remove link ${dir}`, () => fs.unlinkSync(dir));
    else for (const f of fs.readdirSync(src)) {
      const p = path.join(dir, f);
      if (exists(p) && fs.readFileSync(p, 'utf8') === fs.readFileSync(path.join(src, f), 'utf8')) act(`remove ${p}`, () => fs.unlinkSync(p));
    }
    return;
  }
  const empty = !exists(dir) || (fs.lstatSync(dir).isDirectory() && !isLink(dir) && fs.readdirSync(dir).length === 0);
  if (isLink(dir) || empty) {
    if (empty && exists(dir)) act(`remove empty ${dir}`, () => fs.rmdirSync(dir));
    junction(src, dir);
    return;
  }
  // You already have your own agents: copy ours beside them (doctor.mjs reports drift).
  for (const f of fs.readdirSync(src)) {
    const p = path.join(dir, f);
    const want = fs.readFileSync(path.join(src, f), 'utf8');
    if (exists(p) && fs.readFileSync(p, 'utf8') === want) { log(`  ok  ${p}`); continue; }
    if (exists(p)) backup(p);
    act(`copy ${f} -> ${p} (re-run install after editing global/agents)`, () => fs.writeFileSync(p, want));
  }
}

// ---- 4. settings.json ----
function settings() {
  log('4. ~/.claude/settings.json');
  const f = path.join(C, 'settings.json');
  const s = readJSON(f, {});
  const before = JSON.stringify(s);
  const hook = (name) => `node "${fwd(path.join(ROOT, 'global', 'hooks', name))}"`;
  const wanted = [
    ['UserPromptSubmit', hook('coach.mjs'), undefined, 10],
    ['PreToolUse', hook('guard.mjs'), 'Bash|PowerShell', 10],
    ['SessionStart', hook('guard.mjs'), undefined, 10],
    ['PreCompact', hook('session-log.mjs'), undefined, 10],
    ['SessionEnd', hook('session-log.mjs'), undefined, 10],
  ];
  s.hooks = s.hooks || {};
  // drop every nikabrain hook first (also old paths after the repo moved), then add the wanted ones
  for (const ev of Object.keys(s.hooks)) {
    s.hooks[ev] = s.hooks[ev]
      .map((g) => ({ ...g, hooks: (g.hooks || []).filter((h) => !/nikabrain[\\/]+global[\\/]+hooks/.test(h.command || '')) }))
      .filter((g) => g.hooks.length);
    if (!s.hooks[ev].length) delete s.hooks[ev];
  }
  const perms = (s.permissions = s.permissions || {});
  const libRead = `Read(~/${fwd(path.relative(HOME, path.join(ROOT, 'library')))}/**)`;
  const rules = { ask: ['Bash(git push:*)'], allow: [libRead] };
  if (UNINSTALL) {
    for (const k of Object.keys(rules)) if (perms[k]) perms[k] = perms[k].filter((r) => !(k === 'allow' && /nikabrain/.test(r)));
  } else {
    for (const [ev, cmd, matcher, timeout] of wanted) {
      (s.hooks[ev] = s.hooks[ev] || []).push({ ...(matcher ? { matcher } : {}), hooks: [{ type: 'command', command: cmd, timeout }] });
    }
    for (const [k, list] of Object.entries(rules)) {
      perms[k] = perms[k] || [];
      for (const r of list) if (!perms[k].includes(r)) perms[k].push(r);
    }
    // keep transcripts a year: /retro mines the sessions it missed
    if (!s.cleanupPeriodDays || s.cleanupPeriodDays < 365) s.cleanupPeriodDays = 365;
  }
  if (JSON.stringify(s) === before) { log(`  ok  ${f}`); return; }
  if (exists(f)) act(`back up ${f} -> ${path.join(BACKUPS, `settings.json.pre-nikabrain-${today()}`)}`, () => {
    fs.mkdirSync(BACKUPS, { recursive: true });
    const b = path.join(BACKUPS, `settings.json.pre-nikabrain-${today()}`);
    if (!exists(b)) fs.copyFileSync(f, b);
  });
  act(`write ${f}: ${UNINSTALL ? 'nikabrain hooks removed' : 'hooks UserPromptSubmit/PreToolUse/SessionStart/PreCompact/SessionEnd, ask git push, allow ' + libRead + ', cleanupPeriodDays 365'}`,
    () => fs.writeFileSync(f, JSON.stringify(s, null, 2) + '\n'));
}

// ---- 5. git hooks ----
function gitHooks() {
  log('5. git core.hooksPath');
  if (!exists(path.join(ROOT, '.git'))) { log('  nikabrain is not a git repo yet: run `git init` in it, then re-run this'); return; }
  let cur = '';
  try { cur = execFileSync('git', ['-C', ROOT, 'config', 'core.hooksPath'], { encoding: 'utf8' }).trim(); } catch { /* unset */ }
  if (UNINSTALL) { if (cur === '.githooks') act('unset core.hooksPath', () => execFileSync('git', ['-C', ROOT, 'config', '--unset', 'core.hooksPath'])); return; }
  if (cur === '.githooks') { log('  ok  core.hooksPath=.githooks'); return; }
  act('git config core.hooksPath .githooks', () => execFileSync('git', ['-C', ROOT, 'config', 'core.hooksPath', '.githooks']));
}

log(`nikabrain ${UNINSTALL ? 'uninstall' : 'install'} (${APPLY ? 'APPLY' : 'dry run: add --apply to change anything'})`);
log(`  repo: ${ROOT}\n  claude config: ${C}`);
try {
  claudeMd(); skills(); agents(); settings(); gitHooks();
} catch (e) {
  console.error(`FAILED: ${e.message}`);
  process.exit(1);
}
log(APPLY ? `done. Restart Claude Code so CLAUDE.md, skills, agents and hooks load, then run: node "${fwd(path.join(ROOT, 'bin', 'doctor.mjs'))}"`
  : 'nothing changed (dry run). Re-run with --apply.');
